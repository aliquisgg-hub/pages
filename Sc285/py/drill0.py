# %% [markdown]
# ### **showResultList(probResultList)**: <br>　　与えられた「問題と結果」のリストをまとめて表示する関数
# - 引数 probResultList には，askProbList 関数の戻り値と同じ形式の，問題と結果のタプルのリストを与えるものとする．
#   - `[((演算子, 左の数, 右の数, 正解), (解答, 判定結果)), ...]` という形．
# - 戻り値はなし．
# - 表示は，例えば以下のような形式が考えられる（適当にアレンジしてもよい）．
#   ```plaintext
#   問題：7 + 5，解答：12 ― ○
#   問題：8 + 5，解答：15 ― ×，正解は13です．
#   問題：3 + 8，解答：11 ― ○
#   ```

# %%
def showResultList(ProbResultList):
    for probResult in ProbResultList:
        prob, result = probResult
        showResult(prob, result)

