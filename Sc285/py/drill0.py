# %% [markdown]
# ### **showResult(prob, result)**: <br>　　問題と，その結果(解答と判定結果)から，その内容を表示する関数
# - 引数 prob には，makeProb 関数の戻り値と同じ形式の，問題を表すタプルを与えるものとする．
#   - `(演算子, 左の数, 右の数, 正解))` という形式．
# - 引数 result には，askProb 関数の戻り値と同じ形式の，結果(解答と判定結果)を表すタプルを与えるものとする．
#   - `(解答, 判定結果)` という形式．
# - 戻り値はなし．
# - 表示は，例えば以下のような形式が考えられる（適当にアレンジしてもよい）．
#   - 正解の場合:
#     ```plaintext
#     問題：7 + 5，解答：12 ― ○
#     ```
#   - 不正解の場合:
#     ```plaintext
#     問題：8 + 5，解答：15 ― ×，正解は13です．
#     ```

# %%
def showResult(prob, result):
    op, x, y, sol = prob
    ans, judge = result
    if judge:
        print(f"問題：{x} {op} {y}，解答：{ans} ― ○")
    else:
        print(f"問題：{x} {op} {y}，解答：{ans} ― ×，正解は{sol}です．")

#showResult(('+', 7, 5, 12), (12, True))
#showResult(('+', 8, 5, 13), (15, False))

# %% [markdown]
# ### **makeProbList(n)**: <br>　　n個の問題を生成して，そのリストを返す関数
# - 引数 n には，問題数を数値で与える．
# - 戻り値は，「makeProb 関数の戻り値と同じ形式の問題表現」のリスト（長さ n）を返すものとする．
#   - `[(演算子, 左の数, 右の数, 正解), ...]` という形となる．
#   - 例えば，n が 3 なら，`[('+', 7, 5, 12), ('+', 8, 5, 13), ('+', 3, 8, 11)]` のような形のリストを返すはずである．
# - 個々の問題の生成には，makeProb 関数を用いるとよい．
# 
# ※ 同じ問題が重複しない問題リストを作成するには，この関数で工夫するとよい．  
# 　 (重複したときに，問題を作り直させるような仕組みを考える)

# %%
def makeProbList(n):
    probList = []
    while n > 0:
        prob = makeProb()
        probList.append(prob)
        n = n -1
    return probList

#makeProbList(3)     # 例えば [('+', 7, 5, 12), ('+', 8, 5, 13), ('+', 3, 8, 11)] のような形のリストを返すはず．

# %% [markdown]
# ### **askProbList(probList)**: <br>　　与えられた問題リストの問題を順に出題し，出題ごとに解答を入力させ，「問題と結果」のリストを返す関数
# - 引数 probList には，makeProbList 関数の戻り値と同じ形式の，問題表現のリストを与えるものとする．
#   - `[(演算子, 左の数, 右の数, 正解), ...]` という形．
# - 戻り値は，問題と結果のタプルのリストを返すものとする．
#   - 「問題」は，makeProb 関数の戻り値と同じ形式: `(演算子, 左の数, 右の数, 正解)`．
#   - 「結果」は，askProb 関数の戻り値と同じ形式: `(解答, 判定結果)`．
#   - したがって，「問題と結果のタプル」は `((演算子, 左の数, 右の数, 正解), (解答, 判定結果))` という形式．
#   - 結果として，戻り値は `[((演算子, 左の数, 右の数, 正解), (解答, 判定結果)), ...]` という形となる．
# - 個々の問題の出題と解答の入力には，askProb 関数を用いるとよい．

# %%
def askProbList(probList):
    probResultList =[]
    for prob in probList:
        result = askProb(prob)
        probResultList.append((prob, result))
    return probResultList

