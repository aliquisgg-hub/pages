# ## 計算練習プログラムのための部品となる関数を定義する
# 
# - **makeProb()**: 計算練習問題を作る関数
# - **askProb(prob)**: 問題を出題して解答を入力させ，結果(解答と判定結果)を返す関数
# - **showResult(prob, result)**: 問題と，その結果(解答と判定結果)から，その内容を表示する関数
# - **makeProbList(n)**: n個の問題を生成して，そのリストを返す関数
# - **askProbList(probList)**: 与えられた問題リストの問題を順に出題し，出題ごとに解答を入力させ，「問題と結果」のリストを返す関数
# - **showResultList(probResultList)**: 与えられた「問題と結果」のリストをまとめて表示する関数

# %% [markdown]
# ### **makeProb()**: <br>　　計算練習問題を作る関数
# - 引数はなし
# - 戻り値は，作成した問題とする．
#   - `(演算子, 左の数, 右の数, 正解)` という形式のタプルで返すものとする．
#   - `演算子` は `"+"`, `"-"` などの文字列で表すものとする．
#   - `左の数`, `右の数`, `正解` は数値で表すものとする．
#   - 例えば，5 + 3 なら `("+", 5, 3, 8)` というタプルを戻り値として返すことになる．
# - random.randint 関数を使ってランダムに問題を作成する．
# - さしあたって，1～10 の自然数の足し算の問題を作成するものとする．
# 
# ※ 計算練習プログラムを改変して，問題の種類を変えるときは，この関数を修正すればよい．  
# ※ 複数の種類の問題を混在させる場合は，その種類ごとに (異なった名前で)  
# 　 この「計算練習問題を作る関数」を作成し，必要に応じて使い分けるとよい．

# %%
import random

def makeProb():
    x = random.randint(1, 10)
    y = random.randint(1, 10)
    sol = x + y
    return ("+", x, y, sol)

#makeProb()   # 例えば ("+", 5, 3, 8) のようなタプルを返すはず．

# %% [markdown]
# ### **askProb(prob)**: <br>　　問題を出題して解答を入力させ，結果(解答と判定結果)を返す関数
# - 引数 prob には，出題する問題を makeProb 関数の戻り値と同じ形式のタプルで与える．
#   - `(演算子, 左の数, 右の数, 正解)` という形式．
# - 戻り値は，解答とその解答の正誤を判定した結果のタプル `(解答, 判定結果)` とする．
#   - `解答` は解答者が回答した値（数値）とする．
#   - `判定結果` は，解答が正解(と等しい)ならば `True` そうでなければ `False` とする．
#   - 例えば，`("+", 2, 5, 7)` というタプルが引数に与えられ，7 と解答すれば，`(7, True)` というタプルを返すことになる．
# - 出題と解答の入力には，input 関数を用いるとよい．
# 
# ※ input 関数で入力された値（戻り値）は文字列なので，数値に変換するのを忘れないように．

# %%
def askProb(prob):
    op, x, y, sol = prob
    ans = int(input(f"{x} {op} {y} = ? "))
    return (ans, ans==sol)

